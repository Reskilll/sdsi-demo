// Builds the technology logos: web/assets/tech/<id>.svg (for the web UI), png/<id>.png (for PowerPoint) and icons.js (the list).
// Logos come from the Simple Icons package (CC0 files; the brands themselves remain their owners' trademarks), mapped in
// config/tech-icons.json. Any other web/assets/tech/<id>.svg you add by hand is picked up too. Run: npm run icons
import * as si from 'simple-icons';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { closeBrowser, newContext } from '../src/tools/browser.js';

const map = JSON.parse(readFileSync('config/tech-icons.json', 'utf8')) as Record<string, string>;
const all = new Map((Object.values(si) as { slug?: string; svg: string; hex: string }[]).filter((o) => o && o.slug).map((o) => [o.slug!, o]));
mkdirSync('web/assets/tech/png', { recursive: true });
let written = 0;
for (const [id, slug] of Object.entries(map)) {
  if (id.startsWith('_')) continue;
  const icon = all.get(slug);
  if (!icon) { console.warn(`no logo "${slug}" for ${id}`); continue; }
  writeFileSync(`web/assets/tech/${id}.svg`, icon.svg.replace('<svg ', `<svg fill="#${icon.hex}" `));
  written++;
}
const ids = readdirSync('web/assets/tech').filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)).sort();

// PowerPoint cannot rely on SVG, so each logo is also drawn to a PNG with a transparent background.
const ctx = await newContext({ viewport: { width: 200, height: 200 }, deviceScaleFactor: 1 });
const page = await ctx.newPage();
for (const id of ids) {
  const svg = readFileSync(`web/assets/tech/${id}.svg`, 'utf8');
  await page.setContent(`<body style="margin:0;background:transparent"><img id="i" width="160" height="160" style="display:block;margin:20px" src="data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}"></body>`);
  writeFileSync(`web/assets/tech/png/${id}.png`, await page.locator('#i').screenshot({ omitBackground: true, type: 'png' }));
}
await ctx.close(); await closeBrowser();
writeFileSync('web/assets/tech/icons.js', `// Generated by scripts/build-tech-icons.ts. The technology ids that have a logo.\nconst TECH_ICON_IDS = new Set(${JSON.stringify(ids)});\n`);
console.log(`${written} logos written, ${ids.length} available (${ids.length - written} added by hand)`);
