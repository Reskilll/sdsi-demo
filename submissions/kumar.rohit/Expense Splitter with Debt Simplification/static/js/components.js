/**
 * Render an avatar circle.
 */
function Avatar({ name, size }) {
  const s = size || 32;
  const c = avatarColor(name || '?');
  return `<div class="av" style="width:${s}px;height:${s}px;font-size:${s*0.38}px;background:${c.bg};color:${c.color};flex-shrink:0">${getInitials(name)}</div>`;
}

/**
 * Render participant avatars stack.
 */
function AvatarStack(members, max) {
  if (!members || members.length === 0) return '';
  const names = members.map(m => m.name || m.id || m);
  const display = max ? names.slice(0, max) : names;
  let html = '<div class="avatar-stack">';
  display.forEach(n => { html += Avatar({ name: n }); });
  if (max && members.length > max) {
    html += `<div class="av" style="background:var(--color-surface-hover);color:var(--color-text-secondary)">+${members.length - max}</div>`;
  }
  html += '</div>';
  return html;
}

/**
 * Render a modal dialog.
 */
function Modal({ title, body, footer, onClose, wide }) {
  const overlay = document.createElement('div');
  overlay.className = 'modal-overlay';
  overlay.innerHTML = `
    <div class="modal" style="${wide ? 'max-width:800px' : ''}">
      <div class="modal-header">
        <h3 class="modal-title">${title}</h3>
        <button class="modal-close" aria-label="Close">&times;</button>
      </div>
      <div class="modal-body">${body}</div>
      ${footer ? `<div class="modal-footer">${footer}</div>` : ''}
    </div>
  `;
  document.body.appendChild(overlay);

  const close = () => { overlay.remove(); if (onClose) onClose(); };
  overlay.querySelector('.modal-close').onclick = close;
  overlay.addEventListener('click', (e) => { if (e.target === overlay) close(); });
  document.addEventListener('keydown', function esc(e) {
    if (e.key === 'Escape') { close(); document.removeEventListener('keydown', esc); }
  });

  return { overlay, close };
}

/**
 * Debounce helper.
 */
function debounce(fn, ms) {
  let timer;
  return (...args) => { clearTimeout(timer); timer = setTimeout(() => fn(...args), ms); };
}